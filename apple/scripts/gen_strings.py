#!/usr/bin/env python3
"""Generates the native app's typed string accessors from Flutter's ARB files.

lib/l10n/app_en.arb stays the single source of truth for copy on Android and
iOS. This script writes:

  apple/Patterns/Generated/Strings+Generated.swift
      One typed accessor per message, e.g. `strings.navToday` and
      `strings.calmJournalActivity(count: 3)`.

  test/native_l10n_fixture_test.dart
      A Flutter test that renders every message with sample arguments in all
      six languages through the real gen_l10n classes, and (with
      PATTERNS_WRITE_NATIVE_FIXTURES=1) saves them to
      apple/Fixtures/flutter/l10n.json. The Swift tests must reproduce every
      one exactly.

Run after any ARB change: apple/scripts/gen_strings.py
"""

import itertools
import json
import keyword
import os
import re
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
ARB_DIR = os.path.join(REPO, "lib", "l10n")
SWIFT_OUT = os.path.join(REPO, "apple", "Patterns", "Generated", "Strings+Generated.swift")
DART_OUT = os.path.join(REPO, "test", "native_l10n_fixture_test.dart")

LOCALES = [("en", "Locale('en')"), ("pt-BR", "Locale('pt', 'BR')"), ("de", "Locale('de')"),
           ("ja", "Locale('ja')"), ("es", "Locale('es')"), ("fr", "Locale('fr')")]

SWIFT_KEYWORDS = {
    "associatedtype", "class", "deinit", "enum", "extension", "fileprivate", "func", "import", "init",
    "inout", "internal", "let", "open", "operator", "private", "protocol", "public", "rethrows", "static",
    "struct", "subscript", "typealias", "var", "break", "case", "continue", "default", "defer", "do",
    "else", "fallthrough", "for", "guard", "if", "in", "repeat", "return", "switch", "where", "while",
    "as", "catch", "false", "is", "nil", "super", "self", "Self", "throw", "throws", "true", "try",
}


def select_options(message, name):
    """Case keys of `{name, select, ...}` anywhere in the message."""
    options = []
    for match in re.finditer(r"\{\s*" + re.escape(name) + r"\s*,\s*select\s*,", message):
        i = match.end()
        depth = 0
        key = ""
        while i < len(message):
            c = message[i]
            if depth == 0:
                if c == "{":
                    if key.strip():
                        options.append(key.strip())
                    key = ""
                    depth = 1
                elif c == "}":
                    break
                else:
                    key += c
            else:
                if c == "{":
                    depth += 1
                elif c == "}":
                    depth -= 1
            i += 1
    seen = []
    for option in options:
        if option not in seen:
            seen.append(option)
    return seen


def swift_ident(name):
    return f"`{name}`" if name in SWIFT_KEYWORDS else name


def doc_line(text):
    one = text.replace("\n", "\\n")
    return one if len(one) <= 110 else one[:107] + "..."


def main():
    with open(os.path.join(ARB_DIR, "app_en.arb"), encoding="utf-8") as f:
        en = json.load(f)
    keys = [k for k in en if not k.startswith("@")]

    swift = [
        "// Generated by apple/scripts/gen_strings.py from lib/l10n/app_en.arb.",
        "// Do not edit. Run the script after changing any ARB file.",
        "",
        "import PatternsCore",
        "",
        "extension Strings {",
    ]
    dart_cases = []

    for key in keys:
        message = en[key]
        meta = en.get("@" + key, {})
        placeholders = list(meta.get("placeholders", {}).items())
        swift.append(f"    /// {doc_line(message)}")
        if not placeholders:
            swift.append(f"    var {swift_ident(key)}: String {{ string(\"{key}\") }}")
            dart_cases.append((key, []))
            continue

        params = []
        args = []
        samples = []
        for name, info in placeholders:
            kind = info.get("type", "String")
            if kind in ("int", "num", "double"):
                params.append(f"{swift_ident(name)}: Int")
                args.append(f"\"{name}\": .int({swift_ident(name)})")
                samples.append((name, "int", [0, 1, 2, 5, 21, 1000000]))
            else:
                params.append(f"{swift_ident(name)}: String")
                args.append(f"\"{name}\": .string({swift_ident(name)})")
                options = select_options(message, name)
                samples.append((name, "String", options + ["zzzUnknown"] if options else ["Sample"]))
        swift.append(
            f"    func {swift_ident(key)}({', '.join(params)}) -> String "
            f"{{ string(\"{key}\", [{', '.join(args)}]) }}"
        )

        # Vary one placeholder at a time (others at their first sample), plus
        # the full product when it is small.
        combos = []
        product = list(itertools.product(*[s[2] for s in samples]))
        if len(product) <= 60:
            combos = product
        else:
            base = [s[2][0] for s in samples]
            for i, s in enumerate(samples):
                for value in s[2]:
                    combo = list(base)
                    combo[i] = value
                    combos.append(tuple(combo))
        seen = set()
        unique = []
        for combo in combos:
            if combo not in seen:
                seen.add(combo)
                unique.append(combo)
        dart_cases.append((key, [(samples, combo) for combo in unique]))

    swift.append("}")
    swift.append("")
    os.makedirs(os.path.dirname(SWIFT_OUT), exist_ok=True)
    with open(SWIFT_OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(swift))

    def dart_literal(kind, value):
        if kind == "int":
            return str(value)
        return json.dumps(value, ensure_ascii=False).replace("$", "\\$")

    dart = [
        "// Generated by apple/scripts/gen_strings.py. Do not edit.",
        "//",
        "// Renders every message in every language through the real gen_l10n",
        "// classes so the native app can prove its copy matches exactly.",
        "//   PATTERNS_WRITE_NATIVE_FIXTURES=1 flutter test test/native_l10n_fixture_test.dart",
        "",
        "// ignore_for_file: lines_longer_than_80_chars",
        "",
        "import 'dart:convert';",
        "import 'dart:io';",
        "",
        "import 'package:flutter/widgets.dart';",
        "import 'package:flutter_test/flutter_test.dart';",
        "import 'package:patterns/l10n/app_localizations.dart';",
        "",
        "void main() {",
        "  test('write l10n fixture', () async {",
        "    final out = <Map<String, dynamic>>[];",
        "    for (final entry in <String, Locale>{",
    ]
    for tag, locale in LOCALES:
        dart.append(f"      '{tag}': const {locale},")
    dart += [
        "    }.entries) {",
        "      final l = lookupAppLocalizations(entry.value);",
        "      void add(String key, Map<String, Object> args, String value) =>",
        "          out.add({'locale': entry.key, 'key': key, 'args': args, 'value': value});",
    ]
    for key, cases in dart_cases:
        if not cases:
            dart.append(f"      add('{key}', const {{}}, l.{key});")
            continue
        for samples, combo in cases:
            call_args = ", ".join(dart_literal(s[1], v) for s, v in zip(samples, combo))
            map_items = ", ".join(f"'{s[0]}': {dart_literal(s[1], v)}" for s, v in zip(samples, combo))
            dart.append(f"      add('{key}', {{{map_items}}}, l.{key}({call_args}));")
    dart += [
        "    }",
        "    if (Platform.environment['PATTERNS_WRITE_NATIVE_FIXTURES'] == '1') {",
        "      await File('apple/Fixtures/flutter/l10n.json').writeAsString(jsonEncode(out));",
        "    }",
        "    expect(out, isNotEmpty);",
        "  });",
        "}",
        "",
    ]
    with open(DART_OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(dart))

    print(f"{len(keys)} messages -> {os.path.relpath(SWIFT_OUT, REPO)}, {os.path.relpath(DART_OUT, REPO)}")


if __name__ == "__main__":
    sys.exit(main())
